README = """\
# `foo/v0`

## Direction

The provider writes.

```mermaid
## Not a heading
```

## Behavior

- Something.

## Relation Data

[\\[Pydantic Schema\\]](./schema.py)

### Provider
"""


def test_add_generated_sections():
    result = ip.add_generated_sections(README, DATABAGS)
    lines = result.splitlines()
    # The diagram goes at the end of the Direction section, after the existing fence.
    diagram_start = lines.index('flowchart LR') - 1
    assert lines[diagram_start - 2] == '```'
    assert lines.index('## Behavior') > diagram_start
    # The tables go directly under the Relation Data heading, before the hand-written content.
    heading = lines.index('## Relation Data')
    assert lines[heading + 2] == '### Provider application databag'
    assert lines.index('### Provider') > heading
    # The README already links the schema, so the generated content doesn't.
    assert 'Generated from the' not in result


def test_add_generated_sections_direction_ends_at_title():
    readme = '# `foo/v0`\n\n## Direction\n\nThe provider writes.\n\n# Another title\n'
    lines = ip.add_generated_sections(readme, DATABAGS).splitlines()
    assert lines.index('```mermaid') < lines.index('# Another title')


def test_add_generated_sections_relation_data_before_direction():
    readme = (
        '# `foo/v0`\n\n## Relation data\n\nHand-written.\n\n'
        '## Direction\n\nThe provider writes.\n\n## Behavior\n\nStuff.\n'
    )
    lines = ip.add_generated_sections(readme, DATABAGS).splitlines()
    direction = lines.index('## Direction')
    tables = lines.index('### Provider application databag')
    assert lines.index('## Relation data') < tables < lines.index('Hand-written.') < direction
    diagram = lines.index('```mermaid')
    assert direction < diagram < lines.index('## Behavior')


def test_add_generated_sections_without_headings():
    result = ip.add_generated_sections('# `foo/v0`\n\nSome text.\n', DATABAGS)
    lines = result.splitlines()
    heading = lines.index('## Relation data')
    assert lines[heading + 2] == 'Generated from the [Pydantic schema](schema.py).'
    # With no Direction section, the diagram leads the generated relation data.
    assert lines.index('```mermaid') > heading
    assert lines.index('```mermaid') < lines.index('### Provider application databag')


def test_schema_script_handles_both_conventions(tmp_path: pathlib.Path):
    new_style = tmp_path / 'new.py'
    new_style.write_text(
        textwrap.dedent("""\
            from pydantic import BaseModel

            class ProviderAppData(BaseModel):
                host: str

            ProviderUnitData = None
            RequirerAppData = None
            RequirerUnitData = None
        """)
    )
    old_style = tmp_path / 'old.py'
    old_style.write_text(
        textwrap.dedent("""\
            from interface_tester.schema_base import DataBagSchema
            from pydantic import BaseModel

            class Unit(BaseModel):
                address: str

            class RequirerSchema(DataBagSchema):
                unit: Unit
        """)
    )
    misnamed = tmp_path / 'misnamed.py'
    misnamed.write_text(
        textwrap.dedent("""\
            from pydantic import BaseModel

            class ProviderAppAData(BaseModel):
                host: str

            ProviderUnitData = None
            RequirerAppData = None
            RequirerUnitData = None
        """)
    )
    broken = tmp_path / 'broken.py'
    broken.write_text('raise RuntimeError("nope")\n')
    output = subprocess.check_output(
        [
            'uv',
            'run',
            '--no-project',
            '--with-requirements',
            str(_ROOT / 'schema-requirements.txt'),
            str(_ROOT / '.docs' / 'scripts' / 'interface_schemas.py'),
            str(new_style),
            str(old_style),
            str(misnamed),
            str(broken),
        ],
        text=True,
    )
    result = json.loads(output)
    new_bags = result[str(new_style)]['databags']
    assert list(new_bags['provider-app']['properties']) == ['host']
    assert new_bags['requirer-unit'] is None
    old_bags = result[str(old_style)]['databags']
    assert old_bags['provider-app'] is None
    assert old_bags['requirer-app'] is None
    assert list(old_bags['requirer-unit']['properties']) == ['address']
    assert 'does not define ProviderAppData' in result[str(misnamed)]['error']
    assert 'RuntimeError: nope' in result[str(broken)]['error']


def test_recursive_databag_model_lists_its_fields():
    # Pydantic puts a self-referencing model in $defs and makes the schema a $ref to it.
    node = {
        'properties': {
            'name': {'type': 'string'},
            'child': {'anyOf': [{'$ref': '#/$defs/Node'}, {'type': 'null'}], 'default': None},
        },
        'required': ['name'],
        'type': 'object',
    }
    databags = {
        'provider-app': {'$defs': {'Node': node}, '$ref': '#/$defs/Node'},
        'provider-unit': None,
        'requirer-app': None,
        'requirer-unit': None,
    }
    markdown = ip.render_relation_data(databags, link_schema=False)
    assert markdown.splitlines()[:6] == [
        '### Provider application databag',
        '',
        '| Field | Type | Required | Description |',
        '|---|---|---|---|',
        '| `name` | string | yes |  |',
        '| `child` | `Node` object or null | no |  |',
    ]
    # The databag is the Node model, so it isn't documented a second time.
    assert '#### `Node`' not in markdown
    assert 'app: name, child' in ip.render_direction_diagram(databags)


class _Warnings:
    def __init__(self):
        self.messages: list[str] = []

    def warning(self, msg: str, *args: object) -> None:
        self.messages.append(msg % args)


def test_schema_that_cannot_be_rendered_names_the_readme(monkeypatch: pytest.MonkeyPatch):
    warnings = _Warnings()
    monkeypatch.setattr(ip, 'logger', warnings)
    readme = pathlib.Path('interfaces/foo/interface/v0/README.md')
    # A property schema that's a list rather than an object.
    databags: dict[str, typing.Any] = {
        **DATABAGS,
        'provider-app': {'properties': {'host': ['not', 'a', 'schema']}},
    }
    result = ip.with_generated_sections(readme, '# `foo/v0`\n', databags)
    assert result == '# `foo/v0`\n'
    (message,) = warnings.messages
    assert message.startswith(f'{readme}: relation data not generated')
    assert 'AttributeError' in message


def test_schema_that_cannot_be_loaded_names_the_readme(monkeypatch: pytest.MonkeyPatch):
    warnings = _Warnings()
    monkeypatch.setattr(ip, 'logger', warnings)
    readme = pathlib.Path('interfaces/foo/interface/v0/README.md')
    error = ip.SchemaError('Traceback ...\nValueError: schema does not define X')
    result = ip.with_generated_sections(readme, '# `foo/v0`\n', error)
    assert result == '# `foo/v0`\n'
    (message,) = warnings.messages
    assert message.startswith(f'{readme}: relation data not generated')
    assert 'schema does not define X' in message


@pytest.mark.parametrize(
    ('returncode', 'stdout', 'stderr', 'reason'),
    [
        (1, '', 'error: No solution found when resolving', 'No solution found'),
        (0, 'not JSON', '', 'Expecting value'),
    ],
)
def test_schema_script_failure_gives_the_reason(
    monkeypatch: pytest.MonkeyPatch, returncode: int, stdout: str, stderr: str, reason: str
):
    warnings = _Warnings()
    monkeypatch.setattr(ip, 'logger', warnings)

    def run(cmd: list[str], **_kwargs: object) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(cmd, returncode, stdout=stdout, stderr=stderr)

    monkeypatch.setattr(ip.subprocess, 'run', run)
    assert ip._load_schemas(_ROOT, ['interfaces/foo/interface/v0/schema.py']) == {}
    (message,) = warnings.messages
    assert reason in message


def test_load_schemas_keeps_errors_for_each_readme(monkeypatch: pytest.MonkeyPatch):
    output = {
        'a/schema.py': {'databags': dict.fromkeys(DATABAGS)},
        'b/schema.py': {'error': 'ValueError: nope'},
    }

    def run(cmd: list[str], **_kwargs: object) -> subprocess.CompletedProcess[str]:
        return subprocess.CompletedProcess(cmd, 0, stdout=json.dumps(output), stderr='')

    monkeypatch.setattr(ip.subprocess, 'run', run)
    result = ip._load_schemas(_ROOT, list(output))
    assert result['a/schema.py'] == dict.fromkeys(DATABAGS)
    error = result['b/schema.py']
    assert isinstance(error, ip.SchemaError)
    assert str(error) == 'ValueError: nope'


